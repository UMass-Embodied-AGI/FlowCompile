"""
Analyze trace.jsonl file to extract training data from high-quality samples.

For samples where score/metric indicate success, this script:
1. Extracts agent information from tool_metadata in react_steps
2. Collects raw_input_prompt and raw_output for each agent
3. Uses an LLM to judge if the agent performed correctly
4. Saves verified training data to a JSON file
"""

import json
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import List, Dict, Any, Optional, Tuple

import yaml
from openai import AzureOpenAI
from tqdm import tqdm


def _score_is_success(metric: str, score: float) -> bool:
    if metric == "f1":
        return score > 0.5
    return score >= 0.5

def _is_azure_model_config(model_cfg: Any) -> bool:
    if not isinstance(model_cfg, dict):
        return False
    api_type = str(model_cfg.get("api_type", "")).lower()
    if api_type == "azure":
        return True
    required = ("azure_endpoint", "azure_deployment", "api_key", "api_version")
    return all(key in model_cfg for key in required)


def load_azure_config(config_path: str = None, requested_model: Optional[str] = None) -> Tuple[dict, str]:
    """Load Azure OpenAI model configuration from YAML file."""
    if config_path is None:
        # Prefer config.yaml, fallback to config2.yaml
        candidates = [Path("configs/config.yaml"), Path("configs/config2.yaml")]
        for candidate in candidates:
            if candidate.exists():
                config_path = str(candidate)
                break
        if config_path is None:
            config_path = "configs/config.yaml"
    with open(config_path, 'r', encoding='utf-8') as f:
        config = yaml.safe_load(f)

    models = (config or {}).get("models", {})
    if not isinstance(models, dict) or not models:
        raise KeyError(f"No models found in config file: {config_path}")

    azure_models = {
        name: model_cfg
        for name, model_cfg in models.items()
        if _is_azure_model_config(model_cfg)
    }
    if not azure_models:
        raise KeyError(f"No Azure model configs found in {config_path}")

    selected_name = None
    if requested_model:
        if requested_model in azure_models:
            selected_name = requested_model
        else:
            for name, model_cfg in azure_models.items():
                if model_cfg.get("azure_deployment") == requested_model:
                    selected_name = name
                    break

    if selected_name is None:
        for preferred in ("gpt-5", "gpt-5-mini"):
            if preferred in azure_models:
                selected_name = preferred
                break

    if selected_name is None:
        selected_name = next(iter(azure_models))

    return azure_models[selected_name], selected_name


def find_trace_files(path: str) -> List[str]:
    """
    Find all trace.jsonl files in a directory (recursively) or return the file if it's a single file.
    
    Args:
        path: Either a path to a trace.jsonl file or a directory
        
    Returns:
        List of trace file paths found
    """
    path_obj = Path(path)
    
    if path_obj.is_file():
        # Single file provided
        if path_obj.name == 'trace.jsonl' or path_obj.suffix == '.jsonl':
            return [str(path_obj)]
        else:
            return [str(path_obj)]
    elif path_obj.is_dir():
        # Directory provided - find all trace.jsonl files recursively
        trace_files = list(path_obj.rglob('trace.jsonl'))
        trace_files = sorted([str(f) for f in trace_files])
        return trace_files
    else:
        raise FileNotFoundError(f"Path not found: {path}")


def load_trace_file(trace_file_path: str) -> List[Dict[str, Any]]:
    """Load and parse the trace JSONL file."""
    samples = []
    with open(trace_file_path, 'r') as f:
        for line in f:
            if line.strip():
                samples.append(json.loads(line))
    return samples


def extract_agent_data(sample: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    Extract agent information from both workflow types (fixed and meta).
    
    Returns a list of dictionaries containing:
    - agent_name: name of the agent
    - raw_input_prompt: the input prompt given to the agent
    - raw_output: the output generated by the agent
    - problem: the original problem statement
    - full_sample: the complete sample for context in judgment
    """
    agent_data = []
    
    # Check if sample meets quality threshold via unified score/metric
    metric = sample.get('metric')
    score = sample.get('score')
    if metric is None or score is None:
        return agent_data
    if not _score_is_success(metric, float(score)):
        return agent_data
    
    problem = sample.get('problem', '')
    ground_truth = sample.get('ground_truth', '')
    workflow_type = sample.get('workflow_type', 'meta')

    # Extract original sample metadata if available
    original_sample = sample.get('metadata', {}).get('original_sample', {})

    steps = sample.get('steps')
    if isinstance(steps, list) and steps:
        # Handle DSL/fixed workflow traces - data is in 'steps' with 'metadata'
        for step in steps:
            metadata = step.get('metadata', {})
            
            if metadata:
                agent_name = metadata.get('agent', '')
                
                # Get raw LLM interaction (prefer these over old fields)
                raw_llm_prompt = metadata.get('raw_llm_prompt', '')
                raw_llm_output = metadata.get('raw_llm_output', '')
                
                # Fallback to old field names if new ones don't exist
                if not raw_llm_prompt:
                    raw_llm_prompt = metadata.get('raw_input_prompt', '')
                if not raw_llm_output:
                    raw_llm_output = metadata.get('raw_output', '')
                
                # Get processed output and step output
                processed_output = metadata.get('processed_output', '')
                step_output = step.get('output', '')
                
                # Use step output as fallback for processed output
                if not processed_output:
                    processed_output = step_output
                
                input_tokens = metadata.get('input_tokens', 0)
                output_tokens = metadata.get('output_tokens', 0)
                
                # Skip test agent as it doesn't involve LLM calls
                if agent_name == 'test':
                    continue
                
                # Only add if we have minimal required data
                if agent_name and (raw_llm_prompt or processed_output):
                    agent_data.append({
                        'agent_name': agent_name,
                        'agent_input': metadata.get('agent_input', {}),
                        'raw_llm_prompt': raw_llm_prompt,
                        'raw_llm_output': raw_llm_output,
                        'processed_output': processed_output,
                        'step_output': step_output,
                        'problem': problem,
                        'ground_truth': ground_truth,
                        'sample_timestamp': sample.get('timestamp', ''),
                        'step_number': step.get('step', 0),
                        'input_tokens': input_tokens,
                        'output_tokens': output_tokens,
                        'original_sample': original_sample,  # Include original sample metadata
                        'full_sample': sample  # Include full trace for context
                    })
    else:
        # Handle meta-agent workflow traces - data is in 'react_steps' with 'tool_metadata'
        react_steps = sample.get('react_steps', [])
        for step in react_steps:
            tool_metadata = step.get('tool_metadata', {})
            
            if tool_metadata:
                agent_name = tool_metadata.get('agent', '')
                
                # Get raw LLM interaction (prefer these over old fields)
                raw_llm_prompt = tool_metadata.get('raw_llm_prompt', '')
                raw_llm_output = tool_metadata.get('raw_llm_output', '')
                
                # Fallback to old field names if new ones don't exist
                if not raw_llm_prompt:
                    raw_llm_prompt = tool_metadata.get('raw_input_prompt', '')
                if not raw_llm_output:
                    raw_llm_output = tool_metadata.get('raw_output', '')
                
                # Get processed output and tool result
                processed_output = tool_metadata.get('processed_output', '')
                tool_result = step.get('tool_result', '')
                
                # Use tool result as fallback for processed output
                if not processed_output:
                    processed_output = str(tool_result)
                
                input_tokens = tool_metadata.get('input_tokens', 0)
                output_tokens = tool_metadata.get('output_tokens', 0)

                # Skip test agent as it doesn't involve LLM calls
                if agent_name == 'test':
                    continue

                # Only add if we have minimal required data
                if agent_name and (raw_llm_prompt or processed_output):
                    agent_data.append({
                        'agent_name': agent_name,
                        'agent_input': tool_metadata.get('agent_input', {}),
                        'raw_llm_prompt': raw_llm_prompt,
                        'raw_llm_output': raw_llm_output,
                        'processed_output': processed_output,
                        'tool_result': tool_result,
                        'problem': problem,
                        'ground_truth': ground_truth,
                        'sample_timestamp': sample.get('timestamp', ''),
                        'step_number': step.get('step_number', 0),
                        'input_tokens': input_tokens,
                        'output_tokens': output_tokens,
                        'original_sample': original_sample,  # Include original sample metadata
                        'full_sample': sample  # Include full trace for context
                    })

    return agent_data


def judge_agent_correctness(agent_data: Dict[str, Any], client: AzureOpenAI, model: str = "gpt-5-2025-08-07") -> tuple:
    """
    Use LLM to judge whether the specific agent call helped solve the problem in the context of the full trace.
    
    Returns a tuple of:
    - agent_data: the original agent data
    - judgment: dict with is_correct (boolean) and reasoning (str)
    """
    
    # Build context from the full trace
    full_sample = agent_data.get('full_sample', {})
    workflow_type = full_sample.get('workflow_type', 'meta')
    final_answer = full_sample.get('final_answer', 'N/A')
    full_solution = full_sample.get('full_solution', '')
    
    # Extract all agent steps for context - preserve full outputs
    all_steps_context = []
    steps = full_sample.get('steps')
    if isinstance(steps, list) and steps:
        for i, step in enumerate(steps):
            metadata = step.get('metadata', {})
            if metadata:
                agent_name = metadata.get('agent', 'unknown')
                step_output = step.get('output', 'N/A')
                # For programmer, include execution output
                if agent_name == 'programmer':
                    execution_output = metadata.get('execution_output', '')
                    if execution_output:
                        all_steps_context.append(f"Step {i+1} [programmer]:\n  Generated code and executed\n  Execution result: {execution_output}")
                    else:
                        all_steps_context.append(f"Step {i+1} [programmer]: {step_output}")
                else:
                    # Preserve full outputs
                    all_steps_context.append(f"Step {i+1} [{agent_name}]: {step_output}")
    else:
        react_steps = full_sample.get('react_steps', [])
        for i, step in enumerate(react_steps):
            tool_name = step.get('tool_name', 'unknown')
            tool_result = step.get('tool_result', 'N/A')
            thought = step.get('thought', '')
            
            if thought:
                all_steps_context.append(f"Step {i+1} [meta-agent reasoning]: {thought}")
            if tool_name and tool_name != 'finish':
                all_steps_context.append(f"  Tool called: {tool_name}\n  Result: {str(tool_result)}")
    
    trace_context = "\n\n".join(all_steps_context)
    
    # Prepare the actual output shown to user (could be step_output or tool_result)
    actual_agent_output = agent_data.get('step_output') or agent_data.get('tool_result') or agent_data.get('processed_output', 'N/A')
    
    # Determine quality metric based on unified score/metric fields
    metric = full_sample.get('metric', 'N/A')
    score = full_sample.get('score', 'N/A')
    quality_info = f"\n**Score:** {score}\n**Metric:** {metric}"
    
    judgment_prompt = f"""You are an expert evaluator judging whether a specific AI agent call helped solve a problem within a multi-agent workflow.

**Original Problem:**
{agent_data['problem']}

**Ground Truth Answer:**
{agent_data.get('ground_truth', 'N/A')}

**Workflow Final Answer:**
{final_answer}{quality_info}

**Full Workflow Trace (showing all steps leading to the solution):**
{trace_context}

**Current Agent Being Evaluated:**
- Agent Name: {agent_data['agent_name']}
- Step Number: {agent_data['step_number']}
- Agent-Level Input: {agent_data.get('agent_input', {})}

**What the LLM Received (Raw Prompt):**
{agent_data['raw_llm_prompt'] or '(Not captured - possibly error or formatting issue)'}

**What the LLM Generated (Raw Output):**
{agent_data['raw_llm_output'] or '(Not captured - possibly error or formatting issue)'}

**Final Agent Output (after any post-processing):**
{actual_agent_output}

**Evaluation Task:**
Determine if THIS SPECIFIC agent call was helpful and well-executed. Consider:

1. **Understanding**: Did the agent correctly understand its task from the input prompt?
2. **Execution Quality**: Is the agent's raw output (what the LLM generated) sound, logical, and well-reasoned?
3. **Correctness**: Does the output align with the ground truth and contribute to a high-quality final answer?
4. **Value**: In the context of the full workflow, did this agent's contribution help?
5. **Intermediate Utility**: If this is an intermediate step, did it provide useful information for subsequent agents?

**Important Notes:**
- The overall workflow produced a HIGH-QUALITY answer (score/metric indicates success)
- Your job is to assess if THIS PARTICULAR agent call was done well
- An agent can be marked correct even if it's an intermediate step (e.g., programmer generating code, answer_generate producing one of multiple candidate solutions)
- Focus on: Was the agent's output reasonable, helpful, and properly executed given its role?

Respond in JSON format:
{{
    "is_correct": true/false,
    "reasoning": "Brief explanation (2-3 sentences) of whether this agent call was helpful and well-executed"
}}
"""
    
    try:
        response = client.chat.completions.create(
            model=model,
            messages=[
                {"role": "system", "content": "You are an expert evaluator of AI agent performance in multi-agent workflows. Always respond in valid JSON format."},
                {"role": "user", "content": judgment_prompt}
            ],
            response_format={"type": "json_object"},
        )
        
        judgment = json.loads(response.choices[0].message.content)
        return agent_data, judgment
    
    except Exception as e:
        print(f"Error judging agent {agent_data.get('agent_name')} at step {agent_data.get('step_number')}: {e}")
        return agent_data, {"is_correct": False, "reasoning": f"Error during judgment: {str(e)}"}


def process_trace_file(
    trace_file_path: str,
    output_file: str = None,
    config_path: str = "configs/config.yaml",
    model: str = "gpt-5",
    max_samples: int = None,
    num_workers: int = 4
) -> List[Dict[str, Any]]:
    """
    Main processing function to analyze trace file and generate training data with parallel evaluation.
    
    Args:
        trace_file_path: Path to the trace JSONL file
        output_file: Path to save the training data JSON (None to skip saving)
        config_path: Path to Azure OpenAI config YAML file
        model: Azure deployment name to use for judgment
        max_samples: Maximum number of correct samples to process
        num_workers: Number of parallel workers for evaluation (default: 4)
        
    Returns:
        List of training data dictionaries
    """
    # Load Azure OpenAI configuration
    azure_config, selected_model_name = load_azure_config(config_path, requested_model=model)
    
    # Initialize Azure OpenAI client
    client = AzureOpenAI(
        api_key=azure_config['api_key'],
        api_version=azure_config['api_version'],
        azure_endpoint=azure_config['azure_endpoint']
    )
    
    # Use deployment name from config if model not specified
    if model is None or model == selected_model_name:
        model = azure_config['azure_deployment']
    judge_fn = judge_agent_correctness
    
    print(f"Loading trace file: {trace_file_path}")
    samples = load_trace_file(trace_file_path)
    print(f"Loaded {len(samples)} samples")
    
    # Filter for high-quality samples based on unified score/metric
    quality_samples = []
    for s in samples:
        metric = s.get('metric')
        score = s.get('score')
        if metric is None or score is None:
            continue
        if _score_is_success(metric, float(score)):
            quality_samples.append(s)
    
    print(f"Found {len(quality_samples)} high-quality samples (score/metric indicates success)")
    
    if max_samples:
        quality_samples = quality_samples[:max_samples]
        print(f"Processing first {max_samples} high-quality samples")
    
    # Collect all agent data from all samples
    all_agent_data = []
    print("\nExtracting agent data from samples...")
    for sample in quality_samples:
        agent_data_list = extract_agent_data(sample)
        all_agent_data.extend(agent_data_list)
    
    print(f"Total agent data points to evaluate: {len(all_agent_data)}")
    
    # Parallel evaluation with tqdm progress bar
    training_data = []
    approved_count = 0
    
    print(f"\nStarting parallel evaluation with {num_workers} workers...")
    with ThreadPoolExecutor(max_workers=num_workers) as executor:
        # Submit all tasks
        future_to_agent_data = {
            executor.submit(judge_fn, agent_data, client, model): agent_data
            for agent_data in all_agent_data
        }
        
        # Process completed tasks with progress bar
        for future in tqdm(as_completed(future_to_agent_data), total=len(all_agent_data), desc="Evaluating agents"):
            try:
                agent_data, judgment = future.result()
                
                if judgment.get('is_correct', False):
                    training_data.append({
                        'agent_name': agent_data['agent_name'],
                        'agent_input': agent_data.get('agent_input', {}),
                        'raw_llm_prompt': agent_data['raw_llm_prompt'],
                        'raw_llm_output': agent_data['raw_llm_output'],
                        'processed_output': agent_data.get('processed_output', ''),
                        'input_tokens': agent_data['input_tokens'],
                        'output_tokens': agent_data['output_tokens'],
                        'problem': agent_data['problem'],
                        'sample_timestamp': agent_data['sample_timestamp'],
                        'step_number': agent_data['step_number'],
                        'original_sample': agent_data.get('original_sample', {}),  # Include original sample metadata
                        'judgment_reasoning': judgment.get('reasoning', '')
                    })
                    approved_count += 1
            except Exception as e:
                tqdm.write(f"Error processing agent data: {e}")
    
    # Count samples by agent
    agent_counts = {}
    for item in training_data:
        agent_name = item['agent_name']
        agent_counts[agent_name] = agent_counts.get(agent_name, 0) + 1
    
    # Save training data if output_file is specified
    if output_file:
        print(f"\n{'='*60}")
        print("Summary:")
        print(f"  Total samples processed: {len(quality_samples)}")
        print(f"  Total agent data points: {len(all_agent_data)}")
        print(f"  Approved for training: {approved_count}")
        if len(all_agent_data) > 0:
            print(f"  Approval rate: {approved_count/len(all_agent_data)*100:.1f}%")
        print(f"\nApproved samples per agent:")
        for agent_name in sorted(agent_counts.keys()):
            count = agent_counts[agent_name]
            print(f"  - {agent_name}: {count}")
        print(f"{'='*60}")
        
        print(f"\nSaving training data to: {output_file}")
        with open(output_file, 'w') as f:
            json.dump({
                'metadata': {
                    'source_file': trace_file_path,
                    'total_samples': len(samples),
                    'quality_samples': len(quality_samples),
                    'total_agent_data_points': len(all_agent_data),
                    'approved_training_points': approved_count,
                    'judgment_model': model,
                    'num_workers': num_workers
                },
                'training_data': training_data
            }, f, indent=2)
        
        print("✓ Training data saved successfully!")
    else:
        # Silent mode for aggregation
        pass
    
    return training_data


def run_agent_dataset(
    trace_path: str,
    output: Optional[str] = None,
    config_path: str = "configs/config.yaml",
    model: Optional[str] = "gpt-5",
    max_samples: Optional[int] = None,
    num_workers: int = 20,
    individual: bool = False,
) -> List[Dict[str, Any]]:
    """
    Analyze trace.jsonl file(s) and generate training data from correct samples.
    Can process a single file or recursively find all trace.jsonl files in a folder.
    By default, multiple files are aggregated into a single output.
    """

    trace_files = find_trace_files(trace_path)

    if not trace_files:
        raise FileNotFoundError(f"No trace.jsonl files found in {trace_path}")

    print(f"Found {len(trace_files)} trace file(s) to process")

    if len(trace_files) == 1:
        trace_file = trace_files[0]
        if output is None:
            trace_path_obj = Path(trace_file)
            output_file = trace_path_obj.parent / f"{trace_path_obj.stem}_training_data.json"
        else:
            output_file = Path(output)
        output_file.parent.mkdir(parents=True, exist_ok=True)

        print(f"\nProcessing: {trace_file}")
        return process_trace_file(
            trace_file_path=trace_file,
            output_file=str(output_file),
            config_path=config_path,
            model=model,
            max_samples=max_samples,
            num_workers=num_workers,
        )

    if individual:
        print(f"\nProcessing {len(trace_files)} files individually...")

        output_dir = Path(output) if output else None
        if output_dir:
            output_dir.mkdir(parents=True, exist_ok=True)

        combined: List[Dict[str, Any]] = []
        for i, trace_file in enumerate(trace_files, 1):
            print(f"\n[{i}/{len(trace_files)}] Processing: {trace_file}")
            try:
                trace_path_obj = Path(trace_file)
                if output_dir:
                    output_file = output_dir / f"{trace_path_obj.stem}_training_data.json"
                else:
                    output_file = trace_path_obj.parent / f"{trace_path_obj.stem}_training_data.json"

                training_data = process_trace_file(
                    trace_file_path=trace_file,
                    output_file=str(output_file),
                    config_path=config_path,
                    model=model,
                    max_samples=max_samples,
                    num_workers=num_workers,
                )
                combined.extend(training_data)
            except Exception as e:
                print(f"Error processing {trace_file}: {e}")
                continue
        return combined

    # Aggregate all training data into a single output file (DEFAULT for multiple files)
    if output is None:
        input_path = Path(trace_path)
        output_file = input_path / "aggregated_training_data.json"
    else:
        output_file = Path(output)

    output_file.parent.mkdir(parents=True, exist_ok=True)

    print(f"\nProcessing {len(trace_files)} files and aggregating results...")
    aggregated_training_data: List[Dict[str, Any]] = []
    aggregated_metadata = {
        'source_files': trace_files,
        'total_files': len(trace_files),
        'total_samples': 0,
        'total_quality_samples': 0,
        'total_agent_data_points': 0,
        'total_approved_training_points': 0,
        'judgment_model': model,
        'num_workers': num_workers,
        'per_file_stats': [],
    }

    for i, trace_file in enumerate(trace_files, 1):
        print(f"\n[{i}/{len(trace_files)}] Processing: {trace_file}")
        try:
            training_data = process_trace_file(
                trace_file_path=trace_file,
                output_file=None,  # Don't save individual files when aggregating
                config_path=config_path,
                model=model,
                max_samples=max_samples,
                num_workers=num_workers,
            )

            file_stats = {
                'file': trace_file,
                'training_points': len(training_data),
            }
            aggregated_metadata['per_file_stats'].append(file_stats)
            aggregated_training_data.extend(training_data)
            aggregated_metadata['total_approved_training_points'] += len(training_data)

        except Exception as e:
            print(f"Error processing {trace_file}: {e}")
            continue

    print(f"\n{'='*60}")
    print("Aggregation Summary:")
    print(f"  Total files processed: {len(trace_files)}")
    print(f"  Total training points: {len(aggregated_training_data)}")
    print(f"{'='*60}")

    print(f"\nSaving aggregated training data to: {output_file}")
    with open(output_file, 'w') as f:
        json.dump({
            'metadata': aggregated_metadata,
            'training_data': aggregated_training_data,
        }, f, indent=2)

    print("✓ Aggregated training data saved successfully!")
    return aggregated_training_data
